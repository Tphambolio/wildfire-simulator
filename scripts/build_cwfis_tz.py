"""Build ``api/src/firesim_api/services/cwfis_tz_data.py`` from the CWFIS station table.

CWFIS assigns every weather station a fixed "UTC-LST" correction (``tz_correct``, "estimated
from coordinate ranges and maps"; metadata ``WeatherStations_CWFIS_export.xml``) and builds its
daily (noon LST) values from the hour 12 - tz_correct UTC. In several provinces that hour is not
the same for every station and does not follow the legal clock: Saskatchewan (legally UTC-6) is
-6 in the south and east and -7 in the north-west; British Columbia is -8 except 75 eastern
(Mountain-time) stations at -7; Ontario, Quebec, Newfoundland and Labrador and Nunavut are mixed
too. FireSim's noon-LST hour for a point (``routers/weather.py``) takes the value of the nearest
CWFIS station in such a province from the table this script writes.

Usage:
    curl -o cwfis_allstn2026.csv https://cwfis.cfs.nrcan.gc.ca/downloads/fwi_obs/cwfis_allstn2026.csv
    python scripts/build_cwfis_tz.py cwfis_allstn2026.csv

Input: the CWFIS station table (CSV; columns prov, lon, lat, tz_correct). Output: a Python
module with ``SOURCE`` (file name, SHA-256, row counts) and ``STATIONS`` (prov, lat, lon,
tz_correct) for the Canadian provinces/territories whose stations have more than one value.
Provinces with one value are in ``routers/weather.py`` ``_STD_OFFSET_H``. Alberta is left out:
its fire-weather offset is dated and configurable (``services/alberta_time.py``).
"""

from __future__ import annotations

import collections
import csv
import hashlib
import sys
from pathlib import Path

CANADA = {"AB", "BC", "MB", "NB", "NF", "NS", "NT", "NU", "ON", "PE", "QC", "SA", "YT"}
OUT = Path(__file__).resolve().parents[1] / "api" / "src" / "firesim_api" / "services" / "cwfis_tz_data.py"


def main(path: str) -> None:
    raw = Path(path).read_bytes()
    rows = list(csv.DictReader(raw.decode("latin-1").splitlines()))
    by_prov: dict[str, list[tuple[float, float, int]]] = collections.defaultdict(list)
    for r in rows:
        prov = r["prov"].strip()
        if prov not in CANADA:
            continue
        by_prov[prov].append((float(r["lat"]), float(r["lon"]), int(r["tz_correct"])))
    mixed = sorted(p for p, v in by_prov.items() if len({t for *_, t in v}) > 1 and p != "AB")
    counts = {p: dict(sorted(collections.Counter(t for *_, t in by_prov[p]).items())) for p in sorted(by_prov)}
    lines = [
        '"""CWFIS station UTC-LST corrections (``tz_correct``) for provinces with more than one.',
        "",
        "Generated by scripts/build_cwfis_tz.py; do not edit. See that script for the method.",
        '"""',
        "",
        "SOURCE = {",
        f'    "file": "{Path(path).name}",',
        '    "url": "https://cwfis.cfs.nrcan.gc.ca/downloads/fwi_obs/cwfis_allstn2026.csv",',
        f'    "sha256": "{hashlib.sha256(raw).hexdigest()}",',
        '    "retrieved": "2026-10-18",',
        f"    \"counts\": {counts!r},",
        "}",
        "",
        "# (prov, lat, lon, tz_correct) for " + ", ".join(mixed),
        "STATIONS = (",
    ]
    for p in mixed:
        for lat, lon, tz in sorted(set(by_prov[p])):
            lines.append(f'    ("{p}", {lat:.2f}, {lon:.2f}, {tz}),')
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({sum(len(set(by_prov[p])) for p in mixed)} stations: {', '.join(mixed)})")


if __name__ == "__main__":
    main(sys.argv[1])
